"""Derive AX's Python3.11-compatible lock without changing Render's Python3.12 lock."""
import re
from pathlib import Path

ROOT=Path(__file__).resolve().parent.parent


def content():
    original=(ROOT/'backend/requirements.lock').read_text(encoding='utf-8')
    matches=list(re.finditer(r'^numpy==([0-9.]+)$',original,re.MULTILINE))
    if len(matches)!=1:
        raise ValueError('AX NumPy 의존성을 다시 검토하세요. Render 잠금 파일 형식이 변경되었습니다.')
    current=matches[0].group(1)
    # PyPI: 2.4.6 supports >=3.11; 2.5.3 requires >=3.12. Retain Render's pin on >=3.12.
    pin='numpy==2.4.6; python_version < "3.12"\nnumpy=='+current+'; python_version >= "3.12"'
    return ('# AX derived lock: Python >=3.11; generated by scripts/build_ax_requirements.py\n'
        '# NumPy compatibility: https://pypi.org/project/numpy/2.4.6/\n'
        '# Other pins follow backend/requirements.lock; validate AX compatibility after dependency changes.\n'
        +original[:matches[0].start()]+pin+original[matches[0].end():])


if __name__=='__main__':
    (ROOT/'backend/requirements-ax.lock').write_text(content(),encoding='utf-8')
    print('AX dependency lock refreshed; Render lock unchanged.')
