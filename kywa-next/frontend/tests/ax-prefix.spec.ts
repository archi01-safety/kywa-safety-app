import { test, expect } from '@playwright/test';
const prefix=process.env.APP_BASE_PATH || '';
test('AX 경로의 사진·분석·제출·로그인·다운로드·새로고침·홈', async({page},info)=>{
  test.skip(!prefix,'AX prefix build only');
  const failed:string[]=[];
  page.on('response',r=>{if(new URL(r.url()).origin==='http://localhost:8010'&&r.status()>=400)failed.push(`${r.status()} ${new URL(r.url()).pathname}`);});
  await page.goto(prefix+'/#inspect');
  await expect(page.locator('.environment')).toContainText('체험 환경');
  const image=page.locator('.brand img');
  await expect(image).toHaveAttribute('src',prefix+'/kywa_logo.png');
  expect(await image.evaluate((el:HTMLImageElement)=>el.naturalWidth)).toBeGreaterThan(0);
  await page.getByLabel('제출자 성명',{exact:true}).fill('홍길동');
  await page.getByLabel('어떤 위험이 있나요?',{exact:false}).fill('AX 경로 합성 시험 난간 손상');
  await page.getByLabel('현장 사진 선택').setInputFiles({name:'wrong-extension.jpg',mimeType:'image/jpeg',buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aX1cAAAAASUVORK5CYII=','base64')});
  await expect(page.locator('.photo-preview img')).toBeVisible();
  await expect(page.getByRole('button',{name:'KYWA AI 위험요인 분석 시작',exact:true})).toBeEnabled();
  await page.getByRole('button',{name:'KYWA AI 위험요인 분석 시작',exact:true}).click();
  await expect(page.locator('.evaluation-row')).toHaveCount(1);
  await expect(page.getByRole('button',{name:'KYWA AI 안전센터로 데이터 전송',exact:true})).toBeEnabled();
  await page.getByRole('button',{name:'KYWA AI 안전센터로 데이터 전송',exact:true}).click();
  await expect(page.locator('.evaluation-row')).toHaveCount(0);
  await page.goto(prefix+'/#reports');
  await page.getByRole('button',{name:'관리자로 체험하기',exact:false}).click();
  await expect(page.getByRole('button',{name:/Excel 다운로드/})).toBeVisible();
  await page.reload();
  await expect(page.getByRole('button',{name:/Excel 다운로드/})).toBeVisible();
  const download=page.waitForEvent('download');
  await page.getByRole('button',{name:/Excel 다운로드/}).click();
  expect((await download).suggestedFilename()).toMatch(/^KYWA_위험성평가_\d{8}\.xlsx$/);
  await expect(page.getByRole('dialog')).toBeHidden();
  await page.locator('.brand').click();
  expect(new URL(page.url()).pathname).toBe(prefix+'/');
  expect(new URL(page.url()).hash).toBe('#inspect');
  await expect(page.getByLabel('제출자 성명',{exact:true})).toHaveValue('');
  await expect(page.getByLabel('어떤 위험이 있나요?',{exact:false})).toHaveValue('');
  expect(failed).toEqual([]);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
  await page.screenshot({path:info.outputPath('ax-prefix.png'),fullPage:true});
});
