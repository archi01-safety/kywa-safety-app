import {test,expect} from '@playwright/test';
test('KYWA photo pipeline, checked confirmation, reset and late response', async ({page},info)=>{
  test.skip(!!process.env.ORGANIZATION_ID && process.env.ORGANIZATION_ID!=='kywa');
  const paths:string[]=[];
  page.on('request',r=>{if(r.method()==='POST')paths.push(new URL(r.url()).pathname)});
  await page.goto('/');
  await page.getByLabel('제출자 성명',{exact:true}).fill('홍길동');
  await page.getByLabel('어떤 위험이 있나요?',{exact:false}).fill('분전반 정비');
  await page.getByLabel('현장 사진 선택',{exact:true}).setInputFiles({name:'wrong-name.jpg',mimeType:'image/jpeg',buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aZ1cAAAAASUVORK5CYII=','base64')});
  await expect(page.getByAltText('분석 전 사진 미리보기')).toBeVisible();
  await expect(page.getByRole('checkbox',{name:'사진에 남은 얼굴·개인정보가 없는지 확인했습니다.'})).toHaveCount(0);
  await page.getByRole('button',{name:'KYWA AI 위험요인 분석 시작',exact:true}).click();
  await expect(page.locator('.evaluation-row')).toHaveCount(1);
  const check=page.getByRole('checkbox',{name:'사진에 남은 얼굴·개인정보가 없는지 확인했습니다.'});
  await expect(check).toBeChecked();
  const submit=page.getByRole('button',{name:'KYWA AI 안전센터로 데이터 전송',exact:true});
  await check.uncheck();await expect(submit).toBeDisabled();
  await check.check();await expect(submit).toBeEnabled();
  expect(paths.findIndex(x=>x.endsWith('/deidentify'))).toBeLessThan(paths.indexOf('/api/analyses'));
  await expect(page.locator('.submit-bar')).toHaveClass(/next-action/);
  await page.screenshot({path:info.outputPath('processed-review.png'),fullPage:true});
  await page.locator('.brand').click();
  await expect(page.getByLabel('제출자 성명',{exact:true})).toHaveValue('');
  await expect(page.locator('.evaluation-row')).toHaveCount(0);
  await expect(page.getByAltText('제출할 사진 미리보기')).toHaveCount(0);
  let release!:()=>void;
  const gate=new Promise<void>(resolve=>{release=resolve});
  await page.route('**/api/analyses',async route=>{const response=await route.fetch();await gate;await route.fulfill({response});});
  await page.getByLabel('제출자 성명',{exact:true}).fill('홍길동');
  await page.getByLabel('어떤 위험이 있나요?',{exact:false}).fill('늦은 분석 응답');
  await page.getByRole('button',{name:'KYWA AI 위험요인 분석 시작',exact:true}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.getByRole('button',{name:'입력 초기화하고 처음으로'}).click();
  release();
  await expect(page.getByRole('dialog')).toBeHidden();
  await expect(page.getByLabel('제출자 성명',{exact:true})).toHaveValue('');
  await page.waitForTimeout(250);
  await expect(page.locator('.evaluation-row')).toHaveCount(0);
});

test('popup success, optional vibration and keyboard focus',async({page})=>{
  await page.addInitScript(()=>{Object.defineProperty(navigator,'vibrate',{value:(duration:number)=>{(window as unknown as {vibrations:number[]}).vibrations??=[];(window as unknown as {vibrations:number[]}).vibrations.push(duration);return true}})});
  await page.goto('/');
  await page.getByLabel('제출자 성명',{exact:true}).fill('홍길동');
  await page.getByLabel('어떤 위험이 있나요?',{exact:false}).fill('현장 검증');
  const button=page.getByRole('button',{name:'KYWA AI 위험요인 분석 시작',exact:true});
  await button.focus();await button.press('Enter');
  await expect(page.getByRole('dialog')).toBeVisible();
  await expect(page.getByRole('dialog')).toBeHidden({timeout:10000});
  expect(await page.evaluate(()=>(window as unknown as {vibrations:number[]}).vibrations)).toContain(45);
  await expect(page.locator('.message')).toHaveCount(0);
});
