import {test,expect} from '@playwright/test';

const png='iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aZ1cAAAAASUVORK5CYII=';
test('same photo box accepts a second drop, order, limit and plan without reassessment',async({page},info)=>{
  test.skip(!!process.env.ORGANIZATION_ID&&process.env.ORGANIZATION_ID!=='kywa');
  await page.goto('/');
  await page.getByLabel('제출자 성명',{exact:true}).fill('홍길동');
  await page.getByLabel('어떤 위험이 있나요?',{exact:false}).fill('현장 케이블 걸림 위험');
  const box=page.getByLabel('최초 평가 사진 업로드 영역',{exact:true});
  const upload=page.getByLabel('현장 사진 선택',{exact:true});
  await upload.setInputFiles({name:'first.jpg',mimeType:'image/jpeg',buffer:Buffer.from(png,'base64')});
  await expect(page.getByRole('dialog')).toBeHidden();
  await expect(box.locator('.photo-tile')).toHaveCount(1);
  const dropped=await page.evaluateHandle(raw=>{const data=new DataTransfer();data.items.add(new File([Uint8Array.from(atob(raw),c=>c.charCodeAt(0))],'second.png',{type:'image/png'}));return data;},png);
  await box.dispatchEvent('drop',{dataTransfer:dropped});
  await expect(box.locator('.photo-tile')).toHaveCount(2);
  await expect(page.getByRole('dialog')).toBeHidden();
  const before=await box.locator('img').evaluateAll(images=>images.map(i=>(i as HTMLImageElement).src));
  await page.getByRole('button',{name:'사진 2을 대표사진으로 이동',exact:true}).click();
  expect(await box.locator('img').evaluateAll(images=>images.map(i=>(i as HTMLImageElement).src))).toEqual(before.reverse());
  await box.dispatchEvent('drop',{dataTransfer:dropped});
  await expect(box.locator('.photo-tile')).toHaveCount(2);
  await expect(page.getByRole('alert')).toContainText('최대 2장');
  await page.getByRole('button',{name:'KYWA AI 위험요인 분석 시작',exact:true}).click();
  await expect(page.locator('.evaluation-row')).toHaveCount(1);
  await expect(page.getByRole('dialog')).toBeHidden();
  for(const index of [1,2])await expect(page.getByRole('checkbox',{name:`사진 ${index} 개인정보 확인`,exact:true})).toBeChecked();
  const location=`${info.project.name} 복수사진 계획 시험`;
  await page.locator('.evaluation-row').getByLabel('장소',{exact:true}).fill(location);
  await page.getByRole('button',{name:'KYWA AI 안전센터로 데이터 전송',exact:true}).click();
  await expect(page.getByRole('dialog')).toBeHidden();
  await page.getByRole('button',{name:'개선조치 · 재평가',exact:true}).click();
  await page.getByRole('button',{name:'관리자로 체험하기',exact:true}).click();
  await expect(page.getByRole('dialog')).toBeHidden();
  await page.getByRole('button').filter({has:page.getByRole('heading',{name:location,exact:true})}).click();
  await expect(page.locator('.detail-photos img')).toHaveCount(2);
  await expect(page.getByText('개선 후 사진은 최대 1장 등록할 수 있습니다.',{exact:false})).toBeVisible();
  let reassessments=0;page.on('request',request=>{if(request.url().endsWith('/reassess'))reassessments++;});
  await page.getByLabel('조치계획 내용',{exact:true}).fill('다음 점검일까지 배선을 정리할 예정입니다.');
  await page.getByLabel('조치 예정일',{exact:true}).fill('2026-12-01');
  await page.getByRole('button',{name:'조치예정으로 저장',exact:true}).click();
  await expect(page.getByRole('dialog')).toBeHidden();
  await expect(page.locator('.detail-heading')).toContainText('조치예정');
  expect(reassessments).toBe(0);
  await page.screenshot({path:info.outputPath('photo-plan.png'),fullPage:true});
});

test('slow query shows a loading message and a 503 has its own cause and number',async({page})=>{
  test.skip(!!process.env.ORGANIZATION_ID&&process.env.ORGANIZATION_ID!=='kywa');
  await page.goto('/#actions');
  await page.getByRole('button',{name:'관리자로 체험하기',exact:true}).click();
  await expect(page.locator('.record-item').first()).toBeVisible();
  await expect(page.getByRole('dialog')).toBeHidden();
  let release!:()=>void;const gate=new Promise<void>(r=>release=r);
  await page.route('**/api/assessments?*',async route=>{await gate;await route.fulfill({status:503,json:{detail:'Google 저장소가 일시적으로 응답하지 않습니다. 잠시 후 다시 시도해 주세요.',code:'google_unavailable',request_id:'test-request-v11',retryable:false}});});
  await page.getByRole('button',{name:'목록 새로고침',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('평가 목록을 불러오는 중입니다');
  release();
  await expect(page.getByRole('dialog')).toContainText('Google 저장소가 일시적으로 응답하지 않습니다');
  await expect(page.getByRole('dialog')).toContainText('test-request-v11');
  await expect(page.getByRole('dialog')).not.toContainText('입력 내용을 확인해 주세요. (503)');
});
